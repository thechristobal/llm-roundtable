// Reads katex.min.css, base64-encodes all woff2 font files referenced in it,
// and writes a pre-baked TS constant to src/export/katex-inlined.ts.
// Run once after installing/upgrading katex: node scripts/inline-katex-css.mjs

import { readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const katexDist = resolve(__dirname, '../node_modules/katex/dist')

let css = readFileSync(resolve(katexDist, 'katex.min.css'), 'utf8')

let replaced = 0
css = css.replace(/url\(fonts\/([^)]+\.woff2?)\)/g, (_match, filename) => {
  const fontPath = resolve(katexDist, 'fonts', filename)
  const b64 = readFileSync(fontPath).toString('base64')
  const mime = filename.endsWith('.woff2') ? 'font/woff2' : 'font/woff'
  replaced++
  return `url(data:${mime};base64,${b64})`
})

const out = `// Auto-generated by scripts/inline-katex-css.mjs — do not edit manually.
// Re-run after upgrading katex: node scripts/inline-katex-css.mjs
export const inlinedKatexCss = ${JSON.stringify(css)}
`

writeFileSync(resolve(__dirname, '../src/export/katex-inlined.ts'), out)
console.log(`Done. Inlined ${replaced} font references. Output: ${(out.length / 1024).toFixed(0)} KB`)
